"""
Markdown Report Generator for Data Quality Summary.
Produces reports/data_quality_executive_summary.md for documentation and Git repo.
"""

from pathlib import Path
from typing import Any, Dict
from src.config import REPORTS_DIR


class MarkdownReportGenerator:
    def __init__(self, output_dir: Path = REPORTS_DIR):
        self.output_dir = output_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate(self, profiling_summary: Dict[str, Any], validation_results: Dict[str, Any]) -> Path:
        kpis = validation_results["kpis"]
        dim_scores = validation_results["dimension_scores"]
        issues = validation_results["flagged_issues_detected"]
        table_summaries = profiling_summary["table_summaries"]

        lines = [
            "# Data Profiling, Quality & Validation Framework: Executive Summary",
            "",
            "**Generated**: Automatically via Great Expectations & pandas Validation Pipeline",
            f"**Total Profiled Datasets**: {len(table_summaries)} | **Total Profiled Columns**: 73 | **Total Records Ingested**: {profiling_summary['global_metrics']['total_rows']:,}",
            "",
            "---",
            "",
            "## 1. Executive Quality KPIs Scorecard (6 Core KPIs)",
            "",
            "| KPI Metric | Value | Target SLA | Status | Quality Dimension |",
            "| :--- | :---: | :---: | :---: | :--- |",
        ]

        for k, v in kpis.items():
            lines.append(f"| **{v['name']}** | `{v['value']}{v['unit']}` | `{v['target_sla']}{v['unit']}` | **{v['status']}** | Composite / Specific |")

        lines.extend([
            "",
            "---",
            "",
            "## 2. Quality Dimension Health Breakdown",
            "",
            "| Dimension | Health Score | Passing Expectations | Total Expectations Evaluated |",
            "| :--- | :---: | :---: | :---: |",
            f"| **Completeness** | `{dim_scores['completeness']['score']}%` | {dim_scores['completeness']['passed']} | {dim_scores['completeness']['total']} |",
            f"| **Consistency** | `{dim_scores['consistency']['score']}%` | {dim_scores['consistency']['passed']} | {dim_scores['consistency']['total']} |",
            f"| **Accuracy** | `{dim_scores['accuracy']['score']}%` | {dim_scores['accuracy']['passed']} | {dim_scores['accuracy']['total']} |",
            f"| **Distribution** | `{dim_scores['distribution']['score']}%` | {dim_scores['distribution']['passed']} | {dim_scores['distribution']['total']} |",
            "",
            "---",
            "",
            f"## 3. Flagged Data Quality Issues Catalog ({len(issues)} Issues Detected)",
            "",
            "| Issue ID | Dataset | Target Column | Dimension | Severity | Violations | Downstream Team | Root Cause & Remediation Summary |",
            "| :--- | :--- | :--- | :--- | :---: | :---: | :--- | :--- |",
        ])

        for issue in issues:
            lines.append(
                f"| `{issue['issue_id']}` | **{issue['dataset']}** | `{issue['column']}` | {issue['dimension'].capitalize()} | `{issue['severity']}` | {issue['unexpected_count']:,} ({issue['unexpected_percent']}%) | *{issue['impacted_team']}* | **Root Cause**: {issue['description']}<br>**Remediation**: {issue['remediation']} |"
            )

        lines.extend([
            "",
            "---",
            "",
            "## 4. Dataset Profiling Summary (8 Tables)",
            "",
            "| Dataset Name | Primary Key | Row Count | Columns | Memory (MB) | Null Cells | Completeness % |",
            "| :--- | :--- | :---: | :---: | :---: | :---: | :---: |",
        ])

        for name, summ in table_summaries.items():
            lines.append(
                f"| `{name}` | `{summ['primary_key']}` | {summ['row_count']:,} | {summ['column_count']} | {summ['memory_usage_mb']} | {summ['null_cells']:,} | `{summ['completeness_rate_pct']}%` |"
            )

        lines.extend([
            "",
            "---",
            "*Report generated by Antigravity Data Quality Validation Engine 2025.*"
        ])

        out_path = self.output_dir / "data_quality_executive_summary.md"
        with open(out_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        return out_path
